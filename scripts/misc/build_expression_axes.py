def classify(text, rules):
    for name, kws, _ in rules:
        if any(k in text for k in kws):
            return name
    return None


praise, blame, undecided = {}, {}, []
for n, v in ma.items():
    for kind, items, store, rules in (("pros", v.get("pros") or [], praise, D_PRAISE),
                                      ("cons", v.get("cons") or [], blame, D_BLAME)):
        for x in items:
            if not any(k in x for k in EXPR_HINT):
                continue
            if any(g in x for g in NEG):
                continue
            cat = classify(x, rules)
            if cat:
                store.setdefault(cat, []).append({"machine": n, "voice": x})
            else:
                undecided.append((kind, n, x))

