c_out, c_un = {}, []
for n, v in gdl["machines"].items():
    p = v.get("presentation")
    if not p:
        continue
    s = (p.get("escalation") or "").strip()
    t = next((name for name, pat, in [(a, b) for a, b in C_RULES] if s and re.search(pat, s)), None)
    if not t:
        c_un.append(n)
        continue
    c_out.setdefault(t, []).append({"machine": n, "detail": s})
T["昇格の型"] = {k: {"description": C_DESC[k], "count": len(v), "examples": v}
                for k, v in sorted(c_out.items(), key=lambda x: -len(x[1]))}


